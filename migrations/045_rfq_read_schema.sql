-- RFQ data required by the existing buyer list and detail views.
-- Tenant IDs are repeated on child rows so API queries and constraints can
-- keep every RFQ relationship within the authenticated organization.

CREATE TABLE IF NOT EXISTS rfqs (
  id CHAR(36) NOT NULL PRIMARY KEY,
  organization_id CHAR(36) NOT NULL,
  rfq_number VARCHAR(64) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  status ENUM('draft', 'pending_files', 'generating', 'ready', 'sent', 'awaiting_quote', 'quoted', 'awarded', 'cancelled', 'completed') NOT NULL DEFAULT 'draft',
  due_date DATE NULL,
  required_date DATE NULL,
  valid_until DATE NULL,
  requires_samples BOOLEAN NOT NULL DEFAULT FALSE,
  requires_first_article BOOLEAN NOT NULL DEFAULT FALSE,
  requires_quality_report BOOLEAN NOT NULL DEFAULT FALSE,
  allow_partial_quotes BOOLEAN NOT NULL DEFAULT TRUE,
  release_files_generated BOOLEAN NOT NULL DEFAULT FALSE,
  release_files_generated_at DATETIME(3) NULL,
  release_folder_path VARCHAR(2048) NULL,
  billing_address_id CHAR(36) NULL,
  shipping_address_id CHAR(36) NULL,
  shipping_address TEXT NULL,
  shipping_notes TEXT NULL,
  incoterms VARCHAR(128) NULL,
  internal_notes TEXT NULL,
  supplier_notes TEXT NULL,
  sent_at DATETIME(3) NULL,
  sent_by CHAR(36) NULL,
  completed_at DATETIME(3) NULL,
  pdf_url VARCHAR(2048) NULL,
  pdf_generated_at DATETIME(3) NULL,
  awarded_supplier_id CHAR(36) NULL,
  awarded_at DATETIME(3) NULL,
  awarded_by CHAR(36) NULL,
  award_notes TEXT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_by CHAR(36) NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  updated_by CHAR(36) NULL,
  UNIQUE KEY uq_rfqs_org_number (organization_id, rfq_number),
  UNIQUE KEY uq_rfqs_org_id (organization_id, id),
  KEY idx_rfqs_org_created (organization_id, created_at, id),
  KEY idx_rfqs_org_status_created (organization_id, status, created_at, id),
  CONSTRAINT fk_rfq_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_rfq_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_rfq_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_rfq_sender FOREIGN KEY (sent_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_rfq_awarded_by FOREIGN KEY (awarded_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_rfq_awarded_supplier FOREIGN KEY (awarded_supplier_id) REFERENCES suppliers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rfq_items (
  id CHAR(36) NOT NULL PRIMARY KEY,
  organization_id CHAR(36) NOT NULL,
  rfq_id CHAR(36) NOT NULL,
  line_number INT UNSIGNED NOT NULL,
  file_id CHAR(36) NULL,
  part_number VARCHAR(512) NULL,
  description TEXT NULL,
  revision VARCHAR(128) NULL,
  quantity INT UNSIGNED NOT NULL DEFAULT 1,
  uom VARCHAR(64) NOT NULL DEFAULT 'each',
  material VARCHAR(512) NULL,
  finish VARCHAR(512) NULL,
  notes TEXT NULL,
  tolerance_class VARCHAR(128) NULL,
  special_requirements TEXT NULL,
  sw_configuration TEXT NULL,
  release_files_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  release_files_error TEXT NULL,
  step_file_generated BOOLEAN NOT NULL DEFAULT FALSE,
  step_file_path VARCHAR(2048) NULL,
  step_storage_path VARCHAR(2048) NULL,
  step_file_size BIGINT UNSIGNED NULL,
  pdf_file_generated BOOLEAN NOT NULL DEFAULT FALSE,
  pdf_file_path VARCHAR(2048) NULL,
  pdf_storage_path VARCHAR(2048) NULL,
  pdf_file_size BIGINT UNSIGNED NULL,
  attachments JSON NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_rfq_items_line (organization_id, rfq_id, line_number),
  KEY idx_rfq_items_page (organization_id, rfq_id, sort_order, line_number, id),
  KEY idx_rfq_items_file (organization_id, file_id),
  CONSTRAINT fk_rfq_item_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_rfq_item_rfq FOREIGN KEY (organization_id, rfq_id) REFERENCES rfqs(organization_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_rfq_item_file FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE SET NULL,
  CONSTRAINT chk_rfq_item_quantity CHECK (quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rfq_suppliers (
  id CHAR(36) NOT NULL PRIMARY KEY,
  organization_id CHAR(36) NOT NULL,
  rfq_id CHAR(36) NOT NULL,
  supplier_id CHAR(36) NOT NULL,
  sent_at DATETIME(3) NULL,
  sent_by CHAR(36) NULL,
  sent_via VARCHAR(32) NULL DEFAULT 'email',
  viewed_at DATETIME(3) NULL,
  responded_at DATETIME(3) NULL,
  quoted_at DATETIME(3) NULL,
  declined_at DATETIME(3) NULL,
  declined_reason TEXT NULL,
  response_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  contact_email VARCHAR(320) NULL,
  total_quoted_amount DECIMAL(18,6) NULL,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  lead_time_days INT UNSIGNED NULL,
  is_selected BOOLEAN NOT NULL DEFAULT FALSE,
  selected_at DATETIME(3) NULL,
  selected_by CHAR(36) NULL,
  notes TEXT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_rfq_supplier (organization_id, rfq_id, supplier_id),
  KEY idx_rfq_suppliers_page (organization_id, rfq_id, id),
  KEY idx_rfq_suppliers_supplier (organization_id, supplier_id),
  CONSTRAINT fk_rfq_supplier_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_rfq_supplier_rfq FOREIGN KEY (organization_id, rfq_id) REFERENCES rfqs(organization_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_rfq_supplier_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE CASCADE,
  CONSTRAINT fk_rfq_supplier_sender FOREIGN KEY (sent_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_rfq_supplier_selector FOREIGN KEY (selected_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

